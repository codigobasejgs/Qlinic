// Contratação SaaS (simulada): landing → plano → dados → revisão → assinatura → pagamento → onboarding; painéis.
import { test, expect, type Page } from '@playwright/test'
import { asSession, collectErrors, noHorizontalScroll, S } from './helpers'

async function fillPj(page: Page) {
  await page.getByRole('button', { name: 'Preencher com dados fictícios' }).click()
}

test('link Contrato na landing e CTA de cada plano levam ao fluxo correto', async ({ page }) => {
  const errors = collectErrors(page)
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Principal' }).getByRole('link', { name: 'Contrato' }).click()
  await expect(page).toHaveURL(/\/contrato$/)
  await expect(page.getByRole('heading', { level: 1, name: 'Condições gerais de contratação' })).toBeVisible()
  await expect(page.getByText('59.760.458 MARCO ANTONIO BOGGIAN').first()).toBeVisible()
  await expect(page.getByText('59.760.458/0001-91').first()).toBeVisible()
  await expect(page.getByText(/Qlinic Ltda|Código Base Ltda/)).toHaveCount(0)
  await expect(page.getByRole('contentinfo').getByRole('link', { name: 'Contrato' })).toBeVisible()
  await page.goto('/planos')
  for (const name of ['Essencial', 'Profissional', 'Rede']) await expect(page.getByRole('link', { name: `Assinar plano ${name}` }).first()).toBeVisible()
  await page.getByRole('link', { name: 'Assinar plano Rede' }).first().click()
  await expect(page).toHaveURL(/\/contratar\?plano=plan_rede/)
  await expect(page.getByRole('radio', { name: /Rede/ })).toBeChecked()
  expect(errors).toEqual([])
})

test('jornada completa PJ: validação, revisão, aceites, assinatura parcial, pagamento, ativação e painéis', async ({ page }) => {
  const errors = collectErrors(page)
  await page.goto('/contratar?plano=plan_pro')
  await page.getByRole('button', { name: 'Anual' }).click()
  await page.getByRole('button', { name: 'Continuar para dados' }).click()
  // contratada somente leitura
  await expect(page.getByText('somente leitura')).toBeVisible()
  await expect(page.locator('.ctr-readonly input')).toHaveCount(0)
  // validação vinculada ao campo
  await page.getByRole('button', { name: 'Revisar contrato' }).click()
  const legal = page.getByLabel(/Razão social/)
  await expect(legal).toHaveAttribute('aria-invalid', 'true')
  await expect(legal).toBeFocused()
  // CEP: falha de consulta → manual
  await page.getByRole('button', { name: 'Buscar CEP' }).click()
  await expect(page.getByText('Consulta indisponível: preencha manualmente.')).toBeVisible()
  await fillPj(page)
  await page.getByLabel(/Razão social/).fill('Clínica com nome extremamente longo para testar quebra de linha no documento e no resumo Ltda. (fictícia)')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  // voltar preserva
  await page.getByRole('button', { name: 'Voltar ao plano' }).click()
  await page.getByRole('button', { name: 'Continuar para dados' }).click()
  await expect(page.getByLabel(/Razão social/)).toHaveValue(/extremamente longo/)
  await page.getByRole('button', { name: 'Revisar contrato' }).click()
  await expect(page.getByRole('heading', { name: 'Revisão do contrato completo' })).toBeVisible()
  const doc = page.locator('.ctr-paper')
  await expect(doc.getByText('DEMONSTRAÇÃO - NÃO ASSINADO').first()).toBeAttached()
  await expect(doc.getByRole('heading', { name: /Anexo A/ })).toBeVisible()
  await expect(doc.getByRole('heading', { name: /Anexo B/ })).toBeVisible()
  expect(await doc.innerText()).not.toMatch(/\[[^\]]+\]|undefined|null|a definir/i)
  // valor idêntico no resumo e no documento
  const total = (await page.locator('.ctr-summary-desktop .pub-price').innerText()).split('/')[0].trim()
  await expect(doc.getByText(total, { exact: true })).toBeVisible()
  // aceites não pré-marcados e distintos
  const boxes = page.locator('.ctr-accept input[type=checkbox]')
  await expect(boxes).toHaveCount(4)
  for (let i = 0; i < 4; i++) await expect(boxes.nth(i)).not.toBeChecked()
  await page.getByRole('button', { name: 'Assinar (simulação)' }).click()
  await expect(page.getByText(/Marque a concordância/)).toBeVisible()
  await page.getByLabel(/Li e concordo/).check()
  await page.getByLabel(/Declaro possuir poderes/).check()
  await page.getByLabel(/aviso de privacidade/).check()
  await page.getByRole('button', { name: 'Assinar (simulação)' }).dblclick()
  await expect(page.getByRole('heading', { level: 2, name: 'Pagamento', exact: true })).toBeVisible()
  await expect(page.locator('.ctr-state').getByText('Assinado parcialmente')).toBeVisible()
  // pagamento falho → não ativa
  await page.getByRole('button', { name: 'Recusado' }).click()
  await page.getByRole('button', { name: 'Pagar (simulação)' }).click()
  await expect(page.locator('.ctr-state').getByText('Falhou')).toBeVisible()
  await page.getByRole('button', { name: 'Aprovado' }).click()
  await page.getByRole('button', { name: /Tentar pagar novamente/ }).click()
  await expect(page.locator('.ctr-state').getByText('Confirmado')).toBeVisible()
  await expect(page.getByText(/Acesso pago ainda não ativado: aguarda a assinatura da contratada/)).toBeVisible()
  await page.getByRole('button', { name: 'Simular assinatura da contratada' }).click()
  await expect(page.locator('.ctr-state').getByText('Assinado (todas as partes)')).toBeVisible()
  await page.getByRole('button', { name: 'Ver confirmação' }).click()
  await expect(page.getByText('Acesso liberado (simulação)')).toBeVisible()
  // nenhuma informação sensível na URL
  expect(page.url()).not.toMatch(/cpf|cnpj|000\.|@/i)
  await page.getByRole('button', { name: 'Ir para a configuração inicial' }).click()
  await expect(page).toHaveURL(/\/app\/[a-z0-9-]+\/onboarding/)
  // painel da clínica
  await page.goto(page.url().replace(/onboarding$/, 'meu-plano'))
  await expect(page.getByRole('heading', { name: 'Meu plano e contrato' })).toBeVisible()
  await expect(page.getByText('Assinado (todas as partes)').first()).toBeVisible()
  // sem documento sensível no cache do SW
  const cached = await page.evaluate(async () => (await Promise.all((await caches.keys()).map(async (k) => (await (await caches.open(k)).keys()).map((r) => r.url)))).flat())
  expect(cached.filter((u) => /contratar|meu-plano|contrato-final/.test(u))).toEqual([])
  expect(errors).toEqual([])
})


test('@mobile contratação em 360 e 390 px sem rolagem horizontal; resumo compacto expansível', async ({ page }) => {
  for (const width of [360, 390]) {
    await page.setViewportSize({ width, height: 800 })
    await page.goto('/contratar?plano=plan_pro')
    expect(await noHorizontalScroll(page)).toBe(true)
    const sum = page.locator('.ctr-summary-mobile')
    await expect(sum).toBeVisible()
    await sum.locator('summary').first().click()
    await expect(sum.getByText('Ciclo')).toBeVisible()
    await page.goto('/contrato')
    expect(await noHorizontalScroll(page)).toBe(true)
  }
})

